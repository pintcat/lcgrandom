######################################################################################################################
# lcgrandom v1.8 uses a Linear Congruential Generator to calculate random numbers up to 2.147.483.647 (32bit signed) #
# Handshake:                                                                                                         #
# $LCG_LOOP is the number of iterations in which a new random number is generated (default: 1)                       #
# $LCG_MIN contains the minimum value for the random number (default: 0).                                            #
# $LCG_MAX contains the maximum value for the random number (devault: 2147483647).                                   #
# $LCG_DEL is the delimiter which is placed after each random number (default: line feed)                            #
# Usage:                                                                                                             #
# Call LCG_RANDOM() to generate one or more random numbers. These numbers are written to stdout. The LCG algorithm   #
# requires a seed between 0 and 2147483647. By default, the initial seed is generated automatically. You may however #
# call LCG_RANDOM() with a seed of your choice. It's then checked and replaced with an autogenerated one if invalid. #
######################################################################################################################

LCG_DEL="\n"

LCG_RANDOM(){ # checks all input values; corrects them if invalid and generates one or more random numbers accordingly
# IN:  $1 contains the start value for the algorithm which must not exceed 2147483647. If empty or invalid it will be
#       autogenerated by first building a string out of date, time & PID, then calculating a checksum of that string.
#      $LCG_MIN is the minimum value for the random namber. If unset or invalid it's replaced with 0.
#      $LCG_MAX is the maximum value for the random number. Must be above the minimum, but not above the maximum of
#       2147483647. Otherwise it's replaced with that very number.
#      $LCG_LOOP tells how many numbers to be generated. Set it to 0 for an infinite loop.
#      $LCG_DEL is the delimiter which is placed after each random number.
# OUT: Prints the random number(s) with delimiter appended to stdout.
	[ -z "${LCG_LOOP##*[!0-9]*}" ] && LCG_LOOP=2 || LCG_LOOP=$(($LCG_LOOP+($LCG_LOOP!=0)))
	[ -z "${LCG_MIN##*[!0-9]*}" ] || [ $LCG_MIN -ge 2147483647 ] && LCG_MIN=0
	[ -z "${LCG_MAX##*[!0-9]*}" ] || [ $LCG_MAX -le $LCG_MIN ] || [ $LCG_MAX -gt 2147483647 ] && LCG_MAX=2147483647
	[ -z "${1##*[!0-9]*}" ] || [ $1 -gt 2147483647 ] && LCG_SEED=$( (date; printf '%s' "$$") | cksum) || LCG_SEED=$1
	while [ $((LCG_LOOP=$LCG_LOOP-1)) -ne 0 ]; do
		LCG_SEED=$(((${LCG_SEED%" "*}*1103515245+12345)%2147483648)) # calculate next seed state
		printf "%d%b" "$((($LCG_SEED%($LCG_MAX-$LCG_MIN+1))+$LCG_MIN))" "$LCG_DEL" # scale to requested min/max range
	done
	unset LCG_LOOP
}
